    fun loadMyProfile() {
        if (uid.isEmpty()) { _loading.value = false; return }
        viewModelScope.launch {
            try {
                val snap = db.collection("swipeProfiles").document(uid).get().await()
                if (snap.exists()) {
                    val raw = snap.toObject(SwipeProfile::class.java) ?: SwipeProfile()
                    val profile = raw.copy(
                        isCameraShy      = snap.getBoolean("isCameraShy")      ?: false,
                        isProfileComplete = snap.getBoolean("isProfileComplete") ?: false
                    )
                    _myProfile.value = profile
                    refreshDailyCounters(profile)
                    loadFeed(profile.gender)
                } else {
                    // No swipe profile yet — feed will be empty until profile is created
                    _feed.value = emptyList()
                    _myProfile.value = null
                }
            } catch (_: Exception) {
                // Network error — show empty feed
                _feed.value = emptyList()
            } finally {
                _loading.value = false
            }
        }
    }

