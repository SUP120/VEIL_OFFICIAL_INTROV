    fun saveSwipeProfile() {
        if (uid.isEmpty()) return
        viewModelScope.launch {
            isSavingProfile = true
            saveError = null
            try {
                val gameProfileSnap = db.collection("users").document(uid).get().await()
                val alias    = gameProfileSnap.getString("alias")    ?: ""
                // Use gender from Step 0 form if the user selected one; otherwise fall back
                // to the gender stored in their game profile.
                val resolvedGender = gender.ifBlank { gameProfileSnap.getString("gender") ?: "" }
                val age      = (gameProfileSnap.getLong("age") ?: 0L).toInt()

                // If camera shy, store empty photoUrl so the real photo NEVER leaks.
                // SwipeCard also checks isCameraShy on display, but empty URL is a
                // second safety layer — if isCameraShy=true, photo must NOT be in Firestore.
                val photoUrl = if (isCameraShy) "" else {
                    gameProfileSnap.getString("photoUrl")?.takeIf { it.isNotBlank() }
                        ?: auth.currentUser?.photoUrl?.toString()?.takeIf { it.isNotBlank() }
                        ?: gamePhotoUrl.takeIf { it.isNotBlank() }
                        ?: ""
                }

                val profile = SwipeProfile(
                    uid               = uid,
                    alias             = alias,
                    age               = age,
                    gender            = resolvedGender,
                    photoUrl          = photoUrl,          // "" when camera shy
                    isCameraShy       = isCameraShy,
                    avatarResName     = avatarResName,
                    country           = country.trim(),
                    state             = state.trim(),
                    comfortWhen       = comfortWhen.trim(),
                    perfectEvening    = perfectEvening.trim(),
                    openUpWhen        = openUpWhen.trim(),
                    thingsIAvoid      = thingsIAvoid.trim(),
                    placePreference   = placePreference,
                    commStyle         = commStyle,
                    sleepStyle        = sleepStyle,
                    introvertTags     = selectedIntrovertTags.toList(),
                    comfortLevel      = comfortLevel,
                    preferredTimeSlots = selectedTimeSlots.toList(),
                    availableTonight  = availableTonight.trim(),
                    askMeAbout        = askMeAbout.trim(),
                    talkHoursAbout    = talkHoursAbout.trim(),
                    hobbies           = selectedHobbies.toList(),
                    isProfileComplete = true,
                    lastActive        = System.currentTimeMillis()
                )
                db.collection("swipeProfiles").document(uid).set(profile.toMap()).await()
                _myProfile.value = profile
                profileSaved = true
                loadFeed(profile.gender)   // ÃƒÂ¢Ã¢â‚¬Â Ã‚Â load cards immediately after setup
            } catch (e: Exception) {
                saveError = e.message ?: "Failed to save profile"
            } finally {
                isSavingProfile = false
            }
        }
    }

    fun toggleHobby(hobby: String) {
        selectedHobbies = if (hobby in selectedHobbies)
            selectedHobbies - hobby
        else if (selectedHobbies.size < 5) selectedHobbies + hobby
        else selectedHobbies
    }

    fun toggleIntrovertTag(tag: String) {
        selectedIntrovertTags = if (tag in selectedIntrovertTags)
            selectedIntrovertTags - tag
        else if (selectedIntrovertTags.size < 5) selectedIntrovertTags + tag
        else selectedIntrovertTags
    }

    fun toggleTimeSlot(slot: String) {
        selectedTimeSlots = if (slot in selectedTimeSlots)
