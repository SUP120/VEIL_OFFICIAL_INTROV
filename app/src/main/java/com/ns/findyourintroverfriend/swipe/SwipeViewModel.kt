    fun sendCompliment(target: SwipeProfile, message: String = "") {
        val currentCookies = _cookieBalance.value
        if (currentCookies >= 0 && currentCookies < COMPLIMENT_COOKIE_COST) {
            _complimentResult.value = false
            return
        }
        viewModelScope.launch {
            // ── CRITICAL block: balance check + cookie deduction ──────────────
            try {
                val freshSnap    = db.collection("users").document(uid).get().await()
                val freshCookies = snapCookies(freshSnap)
                _cookieBalance.value = freshCookies
                if (freshCookies < COMPLIMENT_COOKIE_COST) {
                    _complimentResult.value = false
                    return@launch
                }
                // Deduct — if this throws, we abort cleanly before writing anything
                db.collection("users").document(uid)
                    .update("cookieBalance", FieldValue.increment(-COMPLIMENT_COOKIE_COST.toLong()))
                    .await()
                _cookieBalance.value = (freshCookies - COMPLIMENT_COOKIE_COST).coerceAtLeast(0)
            } catch (e: Exception) {
                android.util.Log.e("SwipeVM", "Cookie deduction failed: ${e.message}")
                _complimentResult.value = false
                return@launch
            }

            // ── BEST-EFFORT block: secondary writes — none of these should ever ──
            // trigger the "not enough cookies" UI if they fail.
            val today    = LocalDate.now().toString()
            val myAlias  = _myProfile.value?.alias ?: "Someone"
            val myPhoto  = _myProfile.value?.photoUrl ?: ""
            val myAvatar = _myProfile.value?.avatarResName ?: ""
            val now      = System.currentTimeMillis()

            runCatching {
                db.collection("compliments").document(target.uid)
                    .collection("received").document(uid)
                    .set(mapOf(
                        "fromUid"      to uid,
                        "fromAlias"    to myAlias,
                        "fromPhotoUrl" to myPhoto,
                        "fromAvatar"   to myAvatar,
                        "message"      to message,
                        "at"           to now,
                        "isRead"       to false,
                        "status"       to "pending"
                    )).await()
            }

            runCatching {
                db.collection("compliments").document(uid)
                    .collection("sent").document(target.uid)
                    .set(mapOf(
                        "toUid"   to target.uid,
                        "toAlias" to target.alias,
                        "message" to message,
                        "at"      to now,
                        "status"  to "pending"
                    )).await()
            }

            // Use set(merge) so missing swipeProfile doc doesn't throw NOT_FOUND
            runCatching {
                db.collection("swipeProfiles").document(uid).set(
                    mapOf(
                        "dailyComplimentsUsed" to FieldValue.increment(1),
                        "dailyComplimentsDate" to today
                    ),
                    com.google.firebase.firestore.SetOptions.merge()
                ).await()
                _complimentsLeft.value = (_complimentsLeft.value - 1).coerceAtLeast(0)
            }

            runCatching {
                db.collection("swipeLikes").document(uid)
                    .collection("given").document(target.uid)
                    .set(mapOf(
                        "action"           to "compliment",
                        "at"               to now,
                        "toAlias"          to target.alias,
                        "message"          to message,
                        "complimentStatus" to "pending"
                    )).await()
            }

            runCatching { sendComplimentPush(target, message) }

            // ✅ Deduction already succeeded — always signal success
            removeFeedCard(target.uid)
            _complimentResult.value = true
        }
    }

