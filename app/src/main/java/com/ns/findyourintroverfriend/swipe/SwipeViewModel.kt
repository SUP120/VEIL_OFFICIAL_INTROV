    private fun snapCookies(snap: com.google.firebase.firestore.DocumentSnapshot): Int {
        return snap.getLong("cookieBalance")?.toInt()
            ?: snap.getDouble("cookieBalance")?.toInt()
            ?: (snap.get("cookieBalance") as? Number)?.toInt()
            ?: 0
